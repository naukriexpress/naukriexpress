function buildJob(j, i) {
  const slug = slugify(`${j.title}-${j.organization}`);
  const status = j.isDraft ? "draft" : "published";
  return {
    id: id(i + 1),
    slug,
    title: j.title,
    organization: j.organization,
    department: j.department,
    advertisementNumber: j.advertisementNumber,
    logoUrl: "",
    totalVacancies: j.totalVacancies,
    vacancyBreakdown: j.vacancyBreakdown,
    location: j.location,
    eligibility: j.eligibility,
    jobType: j.jobType,
    salary: j.salary,
    applicationFee: j.applicationFee,
    dates: j.dates,
    links: {
      applyOnline: "https://example.gov.in/apply",
      officialNotification: "https://example.gov.in/notification.pdf",
      officialWebsite: "https://example.gov.in",
    },
    content: {
      eligibility: `<p>Candidates must fulfil the eligibility criteria for <strong>${j.title}</strong> as prescribed by ${j.organization}. Please read the official notification carefully before applying.</p>`,
      vacancyDetails: `<p>Total <strong>${j.totalVacancies.toLocaleString("en-IN")}</strong> vacancies are to be filled under this recruitment drive. Post-wise and category-wise break-up is given in the table above.</p>`,
      selectionProcess: `<ol><li>Online Application</li><li>Written / Computer Based Test</li><li>Physical Standard &amp; Efficiency Test (if applicable)</li><li>Document Verification</li><li>Medical Examination</li><li>Final Merit List</li></ol>`,
      howToApply: `<p>Eligible candidates may apply online through the official website before the last date. Keep scanned copies of photograph, signature and certificates ready before starting the application.</p>`,
      importantInstructions: `<ul><li>Read the official notification carefully before applying.</li><li>Ensure you meet the age and qualification criteria on the prescribed date.</li><li>Application fee once paid is non-refundable.</li><li>Keep a printout of the submitted application for future reference.</li></ul>`,
    },
    seo: {
      title: `${j.title} | Apply Online, Eligibility, Last Date`,
      metaDescription: `${j.title} - ${j.totalVacancies.toLocaleString("en-IN")} vacancies. Check eligibility, qualification, age limit, application fee and last date to apply online.`,
    },
    featured: !!j.featured,
    status,
    publishAt: null,
    createdAt: new Date(Date.now() - j.daysAgo * 86400000).toISOString(),
    updatedAt: new Date(Date.now() - j.daysAgo * 86400000).toISOString(),
    views: Math.floor(Math.random() * 5000) + (j.featured ? 4000 : 200),
  };
}

